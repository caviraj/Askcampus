-- CampusAsk initial schema.
--
-- Derived from ARCHITECTURE.md section 4, with corrections. Every departure from
-- the spec SQL is marked "CORRECTION B<n>" and matched to the Phase 1 report.
--
-- This migration cannot run against a bare Postgres: it references auth.users.
-- Apply it with `supabase db reset` or against a real Supabase project.

create extension if not exists vector;

-- ---------------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------------

create table profiles (
  id uuid primary key references auth.users on delete cascade,
  full_name text,
  role text not null default 'staff' check (role in ('staff','admin'))
);

create table documents (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  category text not null check (category in
    ('examinations','admissions','departments','events','academic_processes','general')),
  academic_year text,
  department text,
  file_path text not null,
  file_type text not null,
  -- CORRECTION B: duplicate-upload detection is a Phase 1 definition-of-done edge
  -- case, and AGENTS.md section 14 forbids editing an applied migration. Cheaper
  -- to carry the column from the start than to add it later.
  content_hash text,
  status text not null default 'uploaded'
    check (status in ('uploaded','processing','ready','failed')),
  is_active boolean not null default true,
  error_message text,
  -- CORRECTION B4: was NO ACTION, which blocked deleting a staff auth user
  -- (auth.users -> profiles cascade, then blocked here).
  uploaded_by uuid references profiles(id) on delete set null,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

create table chunks (
  id uuid primary key default gen_random_uuid(),
  document_id uuid not null references documents(id) on delete cascade,
  chunk_index int not null,
  page_number int,
  section_heading text,
  content text not null,
  category text not null,
  embedding vector(768),
  -- The two-argument form is required: to_tsvector(regconfig, text) is IMMUTABLE,
  -- which a generated column demands. The one-argument form is only STABLE and
  -- would fail with "generation expression is not immutable".
  fts tsvector generated always as (to_tsvector('english', content)) stored
);
create index chunks_embedding_idx on chunks using hnsw (embedding vector_cosine_ops);
create index chunks_fts_idx on chunks using gin (fts);
create index chunks_doc_idx on chunks (document_id);

create table queries (
  id uuid primary key default gen_random_uuid(),
  session_id uuid not null,
  question text not null,
  normalized_hash text not null,
  category text,
  answer text,
  -- Deliberately no default: the caller must state the outcome rather than
  -- silently defaulting to a wrong answer.
  answered boolean not null,
  top_score real,
  latency_ms int,
  created_at timestamptz default now()
);
-- CORRECTION B8: FR-8 groups similar questions by this hash, and the repeated-query
-- cache mitigation in PRD section 10 keys on it. It was unindexed.
create index queries_normalized_hash_idx on queries (normalized_hash);
-- GET /admin/queries lists newest-first; without this it is a seq scan plus sort.
create index queries_created_at_idx on queries (created_at desc);

create table query_sources (
  query_id uuid not null references queries(id) on delete cascade,
  rank int not null,
  chunk_id uuid references chunks(id) on delete set null,
  score real,
  -- CORRECTION B: these four columns are copied from the documents/chunks rows at
  -- write time, never generated by the model. With only `chunk_id on delete set
  -- null`, deleting a document left query history permanently unable to name the
  -- document that answered -- while FR-9 promises "sources used" and the source
  -- slip promises a document title.
  -- document_id is intentionally NOT a foreign key: history must outlive the
  -- document, and any FK action would either block the delete or null the value.
  document_id uuid,
  document_title text,
  page_number int,
  section_heading text,
  primary key (query_id, rank)
);

create table unanswered_queries (
  id uuid primary key default gen_random_uuid(),
  query_id uuid references queries(id) on delete cascade,
  normalized_hash text not null,
  question text not null,
  category text,
  status text not null default 'open' check (status in ('open','resolved')),
  -- CORRECTION B4: was NO ACTION, which made DELETE /admin/documents/{id} fail with
  -- a foreign-key violation for any document that had ever resolved a question.
  resolved_by_document uuid references documents(id) on delete set null,
  created_at timestamptz default now()
);
create index unanswered_hash_idx on unanswered_queries (normalized_hash);
create index unanswered_status_created_idx on unanswered_queries (status, created_at desc);

create table feedback (
  query_id uuid primary key references queries(id) on delete cascade,
  helpful boolean not null,
  created_at timestamptz default now()
);

-- ---------------------------------------------------------------------------
-- CORRECTION B1: Row Level Security
--
-- ARCHITECTURE.md section 4 states that documents, chunks, and queries are written
-- only by the backend service role and that admin tables are readable only through
-- backend routes -- but the spec SQL never enabled RLS. Supabase grants `anon` and
-- `authenticated` full DML on every table in `public` by default, and the frontend
-- ships the publishable/anon key, so as written every table was world-readable and
-- world-writable over PostgREST -- including queries.question (student questions)
-- and profiles.role, which would have let anyone promote themselves to admin.
--
-- Enabled with no policies: default-deny for anon and authenticated. The backend
-- uses the service role, which has BYPASSRLS, so nothing in the app changes.
-- The frontend never reads a table directly -- it only talks to Supabase Auth --
-- so this closes the hole without breaking anything.
-- ---------------------------------------------------------------------------

alter table profiles           enable row level security;
alter table documents          enable row level security;
alter table chunks             enable row level security;
alter table queries            enable row level security;
alter table query_sources      enable row level security;
alter table unanswered_queries enable row level security;
alter table feedback           enable row level security;

-- Defence in depth: RLS is the mechanism, these revokes mean a future accidental
-- permissive policy still cannot be reached by the client roles.
revoke all on profiles, documents, chunks, queries, query_sources,
  unanswered_queries, feedback from anon, authenticated;

