-- CORRECTION B5: nothing in the spec ever created a profiles row. Supabase Auth
-- signup inserts into auth.users only, so profiles.role was always absent, the
-- admin gate correctly failed closed, and nobody could ever become an admin.
-- security definer + empty search_path is required: without it the function runs
-- with the invoker's privileges and RLS-enabled profiles rejects the insert.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name)
  values (new.id, new.raw_user_meta_data ->> 'full_name')
  on conflict (id) do nothing;
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- CORRECTION B6: updated_at was `default now()` with no trigger, so it never
-- changed. ARCHITECTURE.md section 5.2 exposes it as `last_updated` in citations
-- and FR-5's newest-document-wins conflict rule depends on it.
create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger documents_set_updated_at
  before update on public.documents
  for each row execute function public.set_updated_at();

-- CORRECTION B7: chunks.category is a denormalized copy of documents.category.
-- PATCH /admin/documents/{id} can change the category, after which the stored
-- chunk values silently drifted and retrieval returned nothing for that document.
-- hybrid_search now filters on d.category (the migration 0002 half of this fix);
-- this trigger keeps the stored column honest for the admin UI.
create or replace function public.sync_chunk_category()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.chunks
     set category = new.category
   where document_id = new.id
     and category <> new.category;
  return new;
end;
$$;

create trigger documents_sync_chunk_category
  after update of category on public.documents
  for each row execute function public.sync_chunk_category();
